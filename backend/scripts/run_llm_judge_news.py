"""Offline batch: DeepSeek semantic verdicts for Case 3 (News) comparisons.

Reads backend/data/news/v7/processed/v6all_event_comparisons.json (generated by
the external gdnews backend and replaced in place on each data swap — never
edit it manually), asks the LLM to judge every comparison whose rule-based class is
A (differ) or B (overlap), and writes a SIDECAR file:

    backend/data/news/v7/processed/llm_verdicts.json

Keys are `event_id::attribute::sorted canonical values` (see llm_judge.verdict_key
and the identical derivation in frontend/src/data/store.js). Existing sidecar
entries are kept so runs RESUME; pass --refresh to re-judge everything.

Usage:
    python backend/scripts/run_llm_judge_news.py --dry-run
    python backend/scripts/run_llm_judge_news.py --limit 5
    python backend/scripts/run_llm_judge_news.py            # full run, resumable

Environment (see backend/.env.example):
    DEEPSEEK_API_KEY  required
    LLM_MODEL         optional (default deepseek-chat)
    LLM_BASE_URL      optional (default https://api.deepseek.com)
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND_DIR))

from llm_judge import (  # noqa: E402  (path bootstrap must run first)
    LLMJudgeError,
    config,
    is_configured,
    judge_consistency,
    utc_now_iso,
    verdict_key,
)

INPUT_PATH = BACKEND_DIR / "data" / "news" / "v7" / "processed" / "v6all_event_comparisons.json"
OUTPUT_PATH = BACKEND_DIR / "data" / "news" / "v7" / "processed" / "llm_verdicts.json"
SCHEMA_VERSION = "news-llm-verdicts-1"
# Only comparisons the rule judge paints red (differ) or yellow (overlap) are
# worth LLM cost. consensus / single-source / not-available fallbacks stay rule-colored.
TARGET_RULE_STATUSES = {"differ", "overlap"}

ATTRIBUTE_LABELS = {
    "participants": "参与者",
    "actions": "动作",
    "time": "时间",
    "place": "地点",
    "cause": "原因",
    "manner": "方式",
    "result": "结果",
    "attributed_to": "消息来源",
    "attitude": "报道态度",
    "roles": "语义角色",
}


def effective_rule_status(status, reports):
    """Mirror of oldStatus() in frontend/src/data/store.js."""
    if status == "different":
        return "differ"
    if status in ("partial_overlap", "missing_in_some_reports"):
        return "overlap"
    if status == "consensus":
        return "consensus"
    present = sum(1 for values in (reports or {}).values() if values)
    return "overlap" if present > 1 else "single_source"


def build_entries(event, comparison):
    """One LLM entry per outlet: display values plus joined evidence sentences."""
    entries, missing = [], []
    for report in event.get("reports", []):
        items = (comparison.get("reports") or {}).get(report.get("report_id")) or []
        values = [str(item.get("display") or "").strip() for item in items]
        values = [value for value in values if value]
        if not values:
            missing.append(report.get("domain") or report.get("report_id"))
            continue
        evidence = " / ".join(
            str(item.get("evidence") or "").strip() for item in items
        ).strip(" /")
        entries.append({
            "source": report.get("domain") or report.get("report_id"),
            "values": values,
            "evidence": evidence or None,
        })
    return entries, missing


def load_sidecar():
    if OUTPUT_PATH.exists():
        data = json.loads(OUTPUT_PATH.read_text(encoding="utf-8"))
        return data.get("verdicts") or {}
    return {}


def write_sidecar(verdicts):
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "schema_version": SCHEMA_VERSION,
        "model": config()["model"],
        "generated_at": utc_now_iso(),
        "verdicts": verdicts,
    }
    OUTPUT_PATH.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


def collect_targets():
    data = json.loads(INPUT_PATH.read_text(encoding="utf-8"))
    targets = []
    for event in data.get("events", []):
        for comparison in event.get("comparisons", []):
            rule_status = effective_rule_status(
                comparison.get("status"), comparison.get("reports")
            )
            if rule_status in TARGET_RULE_STATUSES:
                targets.append((event, comparison, rule_status))
    return targets


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--limit", type=int, default=0, help="judge at most N comparisons (0 = all)")
    parser.add_argument("--dry-run", action="store_true", help="list targets without calling the LLM")
    parser.add_argument("--refresh", action="store_true", help="re-judge keys already in the sidecar")
    args = parser.parse_args()

    if not INPUT_PATH.exists():
        sys.exit(f"input not found: {INPUT_PATH}")

    targets = collect_targets()
    status_counts = Counter(rule_status for _, _, rule_status in targets)
    print(f"target comparisons (rule cls A/B): {len(targets)} {dict(status_counts)}")

    verdicts = load_sidecar()
    pending = [
        (event, comparison, rule_status)
        for event, comparison, rule_status in targets
        if args.refresh
        or verdict_key(
            event.get("event_id"), comparison.get("attribute"), comparison.get("reports")
        ) not in verdicts
    ]
    print(f"sidecar cached: {len(targets) - len(pending)} · pending: {len(pending)}")

    if args.limit and args.limit > 0:
        pending = pending[: args.limit]
        print(f"limit applied -> pending: {len(pending)}")

    if args.dry_run:
        for event, comparison, rule_status in pending:
            entries, missing = build_entries(event, comparison)
            print(
                f"[dry-run] {event.get('event_id')} · {comparison.get('attribute')} · "
                f"rule={rule_status} · {len(entries)} source(s) · missing={missing}"
            )
        return

    if not pending:
        print("nothing to judge; sidecar unchanged.")
        return

    if not is_configured():
        sys.exit(
            "LLM judge not configured. Set DEEPSEEK_API_KEY (see backend/.env.example); "
            "if the openai SDK is missing run: pip install -r backend/requirements.txt"
        )

    judged = Counter()
    try:
        for index, (event, comparison, rule_status) in enumerate(pending, 1):
            event_id = event.get("event_id")
            attribute = comparison.get("attribute")
            entries, missing = build_entries(event, comparison)
            result = judge_consistency(
                event.get("canonical_name") or event_id,
                ATTRIBUTE_LABELS.get(attribute, attribute),
                entries,
                missing,
            )
            verdicts[verdict_key(event_id, attribute, comparison.get("reports"))] = {
                "verdict": result["verdict"],
                "reason": result["reason"],
                "rule_status": rule_status,
                "event_id": event_id,
                "attribute": attribute,
                "judged_at": utc_now_iso(),
            }
            judged[result["verdict"]] += 1
            note = "" if result["verdict"] == "consistent" else f" ({result['reason'][:60]})"
            print(
                f"[{index}/{len(pending)}] {event_id} · {attribute} · rule={rule_status} -> "
                f"{result['verdict']}{note}"
            )
            # Checkpoint after every call so an interrupted run resumes anywhere.
            write_sidecar(verdicts)
    except LLMJudgeError as exc:
        write_sidecar(verdicts)
        sys.exit(f"aborted: {exc}")

    print(f"done. verdicts: {dict(judged)} · sidecar: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
